// Generates docs/API.md for the families that have a `variant` prop, straight from the JSDoc contracts
// in src/library (the same parser the gallery's Props tab uses). Run with `npm run docs:api`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { parseTypedefs } from '../src/gallery/engine/parseDocs.js'

const lib = new URL('../src/library/components/', import.meta.url)
const typedefs = (family) => parseTypedefs(readFileSync(new URL(`${family}/types.js`, lib), 'utf8'))
const registryOf = (family) => readFileSync(new URL(`${family}/variants/index.js`, lib), 'utf8')

const tidy = (text) => text.replace(/import\([^)]*\)\./g, '').replace(/\|/g, '\\|').replace(/\s+/g, ' ')
const isCallback = (prop) => /=>/.test(prop.type) || /^on[A-Z]/.test(prop.name)

function table(props) {
  const rows = props.map(
    (prop) =>
      `| \`${prop.name}\` | ${prop.optional ? '' : '**yes**'} | \`${tidy(prop.type) || '—'}\` | ${prop.default ? `\`${prop.default}\`` : ''} | ${tidy(prop.description)} |`,
  )
  return ['| Prop | Required | Type | Default | Description |', '| --- | --- | --- | --- | --- |', ...rows].join('\n')
}

const families = [
  { name: 'Navbar', dir: 'Navbar', props: 'NavbarProps', variants: 'navbarVariants', note: 'Header with brand, links, search and account / wishlist / cart actions.' },
  { name: 'ProductCard', dir: 'ProductCard', props: 'ProductCardProps', variants: 'productCardVariants', note: 'One product. Presentational: your page owns the cart and the wishlist.' },
  { name: 'ProductGrid', dir: 'ProductGrid', props: 'ProductGridProps', variants: 'productCardVariants', note: 'List of cards; `variant` selects the card design. Forwards card props.' },
  { name: 'Sidebar', dir: 'Sidebar', props: 'SidebarProps', extra: 'CollapsibleSidebarProps', variants: 'sidebarVariants', note: 'Category list and filter groups. Your page owns the category and filter state.' },
  { name: 'Footer', dir: 'Footer', props: 'FooterProps', variants: 'footerVariants', note: 'Site footer.' },
]

const out = [
  '# Variant families: API reference',
  '',
  '> Generated by `npm run docs:api` from the JSDoc in `src/library/components/*/types.js`. Edit the JSDoc, not this file.',
  '',
  'Required props are marked **yes**. Callbacks (props that are functions) are listed separately: the library never',
  'changes your data, it calls these and you update your own state.',
  '',
]

for (const family of families) {
  const defs = typedefs(family.dir)
  const main = defs.get(family.props)
  const defaultName = registryOf(family.dir === 'ProductGrid' ? 'ProductCard' : family.dir).match(/DEFAULT_\w+ = '(\w+)'/)?.[1]
  const registrySource = registryOf(family.dir === 'ProductGrid' ? 'ProductCard' : family.dir)
  const names = [...registrySource.match(/export const \w+Variants = \{([\s\S]*?)\n\}/)[1].matchAll(/^\s*(\w+):/gm)].map((match) => match[1])
  const aliasNames = [...(registrySource.match(/VariantAliases = \{([^}]*)\}/)?.[1] ?? '').matchAll(/(\w+):/g)].map((match) => match[1])
  const variantProp = {
    name: 'variant',
    optional: true,
    type: [...names, ...aliasNames].map((name) => `'${name}'`).join('|'),
    default: `'${defaultName}'`,
    description: `Design to render.${aliasNames.length ? ` ${aliasNames.map((name) => `\`${name}\``).join(', ')} are accepted aliases.` : ''} Unknown values fall back to the default and warn in development.`,
  }
  const callbacks = main.props.filter(isCallback)
  const data = [variantProp, ...main.props.filter((prop) => !isCallback(prop) && prop.name !== 'variant')]

  out.push(`## ${family.name}`, '', family.note, '', '```jsx', `import { ${family.name} } from 'ecom-ui-kit'`, '```', '')
  out.push(`Default variant: \`${defaultName}\`. See "Choosing a variant" in the README for the names and fallback rules.`, '')
  const required = main.props.filter((prop) => !prop.optional).map((prop) => `\`${prop.name}\``)
  out.push(`**Required:** ${required.length ? required.join(', ') : 'none'}`, '')
  out.push('### Props', '', table(data), '')
  if (callbacks.length) out.push('### Callbacks', '', table(callbacks), '')
  if (family.extra) {
    out.push(`### Extra props (\`collapsible\` variant only)`, '', table(defs.get(family.extra).props), '')
  }
  const shapes = [...defs.values()].filter((def) => def.name !== family.props && def.name !== family.extra && !def.extras && !/Props$/.test(def.name))
  if (shapes.length) {
    out.push('### Data shapes', '')
    for (const shape of shapes) {
      out.push(`**\`${shape.name}\`**${shape.description ? `: ${tidy(shape.description)}` : ''}`, '')
      out.push(shape.props.length ? table(shape.props) : `\`${tidy(shape.alias ?? '')}\``, '')
    }
  }
}

mkdirSync(new URL('../docs/', import.meta.url), { recursive: true })
writeFileSync(new URL('../docs/API.md', import.meta.url), `${out.join('\n').trimEnd()}\n`)
console.log('Wrote docs/API.md')
